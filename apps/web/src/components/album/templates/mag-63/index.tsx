// 信息,写成确定性算法而非随机,保证同一本书每次渲染出的条形码一样。
const BARCODE_WIDTHS = [
  3, 1, 2, 1, 1, 4, 1, 2, 3, 1, 1, 2, 4, 1, 3, 1, 2, 1, 1, 3, 2, 1, 4, 1, 2, 3, 1, 1, 2, 1,
];
const BARCODE_GAP = 2;
const BARCODE_BOX_WIDTH = 130;
const BARCODE_BOX_HEIGHT = 38;
const BARCODE_UNIT =
  BARCODE_BOX_WIDTH /
  (BARCODE_WIDTHS.reduce((sum, w) => sum + w, 0) + BARCODE_GAP * BARCODE_WIDTHS.length);

function barcodeBars(): { left: number; width: number }[] {
  let cursor = 0;
  const bars: { left: number; width: number }[] = [];
  BARCODE_WIDTHS.forEach((w, i) => {
    const slotWidth = (w + BARCODE_GAP) * BARCODE_UNIT;
    if (i % 2 === 0) bars.push({ left: cursor, width: w * BARCODE_UNIT });
    cursor += slotWidth;
  });
  return bars;
}
