const SANS_EN = '&quot;Work Sans&quot;, &quot;Noto Sans SC&quot;, &quot;PingFang SC&quot;, sans-serif';
const YEAR = new Date().getFullYear();

// 条形码是纯装饰,不编码任何信息,右下 130×38、与字标底边对齐。画法必须确定性
// (同一本书每次渲染必须一样,不能用 Math.random):30 个单位宽度轮流当「画」/「留白」
// (偶数下标画条、奇数下标留白),每个单位额外带 2 个单位的间隔,单位像素 =
// 130 / Σ(width+gap)。跟 YEAR 同一套「模块加载时算一次、拼进模板字符串」的写法
// (见下 `renderBarcodeBars`)——不手写 15 条 div 的坐标,那样改一次 widths 就要
// 重算一遍数字,人工算容易错。
const BARCODE_WIDTHS = [
  3, 1, 2, 1, 1, 4, 1, 2, 3, 1, 1, 2, 4, 1, 3, 1, 2, 1, 1, 3, 2, 1, 4, 1, 2, 3, 1, 1, 2, 1,
];
const BARCODE_GAP = 2; // 间隔,单位同 widths
const BARCODE_BOX_WIDTH = 130; // px,与下方容器 width:130px 对应
const BARCODE_BOX_HEIGHT = 38; // px,与下方容器 height:38px 对应
const BARCODE_UNIT =
  BARCODE_BOX_WIDTH /
  (BARCODE_WIDTHS.reduce((sum, w) => sum + w, 0) + BARCODE_GAP * BARCODE_WIDTHS.length);

// 偶数下标画条、奇数下标留白;条只在偶数下标输出一个绝对定位 div,currentColor
// 跟随页根墨色。结果在模块加载时算好一次拼进下面的模板字符串(静态产物,不依赖
// 运行时 JS——模板本体就是一份普通字符串)。
function renderBarcodeBars(): string {
  let cursor = 0;
  const bars: string[] = [];
  BARCODE_WIDTHS.forEach((w, i) => {
    const slotWidth = (w + BARCODE_GAP) * BARCODE_UNIT;
    if (i % 2 === 0) {
      const left = cursor.toFixed(1);
      const width = (w * BARCODE_UNIT).toFixed(1);
      bars.push(
        `<div style="position:absolute;left:${left}px;top:0px;width:${width}px;height:${BARCODE_BOX_HEIGHT}px;background:currentColor"></div>`,
      );
    }
    cursor += slotWidth;
  });
  return bars.join('');
}

